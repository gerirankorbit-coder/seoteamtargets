#!/usr/bin/env node
// Local staging in one command:
//
//   npm run dev:staging     start (or reuse) the local staging DB, then run the app on
//                           http://localhost:3001 (the app seeds test data on first start)
//   npm run seed:staging    reset the test data, then exit
//
// The database lives in .staging-db/ (git-ignored) and survives restarts.
//   Linux:         FerretDB (MongoDB-compatible) with SQLite files in .staging-db/ferret-data
//   Windows/macOS: real mongod — from PATH, or downloaded once into .staging-db/tools
// Ctrl+C stops the app and the database this script started.
'use strict';
const fs           = require('fs');
const path         = require('path');
const net          = require('net');
const crypto       = require('crypto');
const { spawn, spawnSync } = require('child_process');

const ROOT     = path.resolve(__dirname, '..');
const DB_DIR   = path.join(ROOT, '.staging-db');
const ENV_FILE = path.join(ROOT, '.env.staging');
const DB_PORT  = 27018;
const FERRET_VERSION = 'v1.24.0';
const MONGOD_VERSION = '7.0.14';
const seedOnly = process.argv.includes('--seed');

const log = msg => console.log(`[staging] ${msg}`);

// ── 1. .env.staging (created once, never committed) ──────────────────────────
function ensureEnvFile() {
  if (fs.existsSync(ENV_FILE)) return;
  fs.writeFileSync(ENV_FILE, [
    '# Local staging settings — generated by scripts/dev-staging.js. Git-ignored; never commit.',
    'APP_ENV=staging',
    'PORT=3001',
    `MONGODB_URI=mongodb://127.0.0.1:${DB_PORT}/`,
    'MONGODB_DB_NAME=rankorbit_staging',
    `SESSION_SECRET=${crypto.randomBytes(32).toString('hex')}`,
    '',
  ].join('\n'));
  log('created .env.staging');
}

// ── 2. Local database ─────────────────────────────────────────────────────────
function portOpen(port) {
  return new Promise(resolve => {
    const s = net.connect({ host: '127.0.0.1', port }, () => { s.end(); resolve(true); });
    s.on('error', () => resolve(false));
  });
}

async function waitForPort(port, ms, child) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    if (child && child.exitCode !== null) return false;
    if (await portOpen(port)) return true;
    await new Promise(r => setTimeout(r, 300));
  }
  return false;
}

function download(url, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  log(`downloading ${url}`);
  const r = spawnSync('curl', ['-fsSL', '-o', dest + '.part', url], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`download failed: ${url}`);
  fs.renameSync(dest + '.part', dest);
}

function onPath(cmd) {
  const r = spawnSync(process.platform === 'win32' ? 'where' : 'which', [cmd], { encoding: 'utf8' });
  return r.status === 0 ? r.stdout.split(/\r?\n/)[0].trim() : null;
}

function ferretCommand() {
  const arch = { x64: 'amd64', arm64: 'arm64' }[process.arch];
  if (!arch) throw new Error(`unsupported CPU architecture: ${process.arch}`);
  const bin = path.join(DB_DIR, 'tools', `ferretdb-${FERRET_VERSION}`);
  if (!fs.existsSync(bin)) {
    download(`https://github.com/FerretDB/FerretDB/releases/download/${FERRET_VERSION}/ferretdb-linux-${arch}`, bin);
    fs.chmodSync(bin, 0o755);
  }
  const data = path.join(DB_DIR, 'ferret-data');
  fs.mkdirSync(data, { recursive: true });
  return [bin, ['--handler=sqlite', `--sqlite-url=file:${data}/`, `--listen-addr=127.0.0.1:${DB_PORT}`,
                '--telemetry=disable', '--log-level=warn', '--debug-addr=-', `--state-dir=${DB_DIR}`]];
}

async function mongodCommand() {
  let bin = onPath('mongod');
  if (!bin) {
    const tools = path.join(DB_DIR, 'tools');
    const pkg   = path.join(tools, 'node_modules', 'mongodb-memory-server-core');
    if (!fs.existsSync(pkg)) {
      log('installing the MongoDB downloader (one time)…');
      fs.mkdirSync(tools, { recursive: true });
      const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
      const r = spawnSync(npm, ['install', '--no-save', '--prefix', tools, 'mongodb-memory-server-core@10'],
                          { stdio: 'inherit', shell: process.platform === 'win32' });
      if (r.status !== 0) throw new Error('could not install mongodb-memory-server-core');
    }
    process.env.MONGOMS_DOWNLOAD_DIR = path.join(tools, 'mongodb-binaries');
    process.env.MONGOMS_VERSION      = process.env.MONGOMS_VERSION || MONGOD_VERSION;
    const { MongoBinary } = require(pkg);
    log('getting mongod (downloads once)…');
    bin = await MongoBinary.getPath();
  }
  const data = path.join(DB_DIR, 'mongo-data');
  fs.mkdirSync(data, { recursive: true });
  return [bin, ['--dbpath', data, '--port', String(DB_PORT), '--bind_ip', '127.0.0.1']];
}

async function ensureDb() {
  if (await portOpen(DB_PORT)) { log(`reusing database already running on port ${DB_PORT}`); return null; }
  const [cmd, args] = process.platform === 'linux' ? ferretCommand() : await mongodCommand();
  const logFile = path.join(DB_DIR, 'db.log');
  const out     = fs.openSync(logFile, 'a');
  const child   = spawn(cmd, args, { stdio: ['ignore', out, out] });
  if (!(await waitForPort(DB_PORT, 30000, child))) {
    child.kill();
    throw new Error(`database did not start — see ${path.relative(ROOT, logFile)}`);
  }
  log(`database started on 127.0.0.1:${DB_PORT} (data in .staging-db/)`);
  return child;
}

// ── 3. Seed + app ─────────────────────────────────────────────────────────────
function runSeed() {
  const r = spawnSync(process.execPath, [path.join(__dirname, 'seed-staging.js')],
                      { stdio: 'inherit', cwd: ROOT, env: { ...process.env, DOTENV_CONFIG_PATH: ENV_FILE } });
  if (r.status !== 0) throw new Error('seed failed');
}

async function main() {
  fs.mkdirSync(DB_DIR, { recursive: true });
  ensureEnvFile();
  const db = await ensureDb();
  const stopDb = () => { if (db && db.exitCode === null) db.kill(); };
  process.on('exit', stopDb);

  try {
    if (seedOnly) runSeed();
  } catch (e) { stopDb(); throw e; }
  if (seedOnly) { stopDb(); return; }

  const app = spawn(process.execPath, ['-r', 'dotenv/config', 'server.js', `dotenv_config_path=${ENV_FILE}`],
                    { stdio: 'inherit', cwd: ROOT });
  const shutdown = () => { app.kill('SIGINT'); };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
  app.on('exit', code => { stopDb(); process.exit(code || 0); });
}

main().catch(err => { console.error(`[staging] ✗ ${err.message}`); process.exit(1); });
